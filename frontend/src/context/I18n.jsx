const I18nContext = createContext(null)
export const useI18n = () => useContext(I18nContext)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem('cw-lang')
    return ['en', 'hi', 'gu'].includes(saved) ? saved : 'en'
  })

  useEffect(() => {
    document.documentElement.lang = lang === 'en' ? 'en' : `${lang}-IN`
  }, [lang])

  const value = useMemo(() => {
    const t = (key, params = {}) => {
      let values = params
      let source = translations[lang]?.[key]
      if (!source && typeof key === 'string') {
        const eta = key.match(/^Arrives in about (\d+) min$/)
        const confirmation = key.match(/^Please confirm this order within (\d+) minutes, or it will be cancelled automatically\.$/)
        const noResponse = key.match(/^No response: order was not confirmed within (\d+) minutes$/)
        const paymentTimeout = key.match(/^Payment was not completed within (\d+) minutes$/)
        if (eta) {
          source = translations[lang]?.['Arrives in about {minutes} min']
          values = { ...params, minutes: eta[1] }
        } else if (confirmation) {
          source = translations[lang]?.['Please confirm this order within {minutes} minutes, or it will be cancelled automatically.']
          values = { ...params, minutes: confirmation[1] }
        } else if (noResponse) {
          source = translations[lang]?.['No response: order was not confirmed within {minutes} minutes']
          values = { ...params, minutes: noResponse[1] }
        } else if (paymentTimeout) {
          source = translations[lang]?.['Payment was not completed within {minutes} minutes']
          values = { ...params, minutes: paymentTimeout[1] }
        }
      }
      source ||= key
      return source.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`))
    }
    const localizeItem = (item) => {
      const localized = productTranslations[lang]?.[item.id]
      return localized ? { ...item, name: localized[0], desc: localized[1] } : item
    }
    const itemName = (id, fallback) => productTranslations[lang]?.[id]?.[0] || fallback
    return {
      lang,
      setLang: (next) => {
        if (!['en', 'hi', 'gu'].includes(next)) return
        localStorage.setItem('cw-lang', next)
        setLangState(next)
      },
      t,
      localizeItem,
      itemName,
    }
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}
